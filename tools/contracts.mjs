import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Rust owns all wire shapes. Check mode compares in memory and never writes outputs.
const source = JSON.parse(execFileSync('cargo', ['run', '--locked', '--quiet', '-p', 'collector-server', '--example', 'export-contracts'], { encoding: 'utf8', maxBuffer: 10_000_000 }));
const outputs = new Map();
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
outputs.set('contracts/openapi/core-v1.json', json(source.openapi));
const ajv = new Ajv2020({ code: { source: true, esm: true }, strict: true });
// Rust emits this annotation; integer/minimum/maximum carry the actual constraint.
ajv.addFormat('uint32', true);
ajv.addFormat('int64', true);
// Rust f64 annotation; AJV's strict number type check rejects NaN/Infinity.
ajv.addFormat('double', true);
const validators = { validateHealth: 'HealthDocument', validateCapabilities: 'CapabilityDocument', validateApiError: 'ApiError' };
for (const name of Object.keys(source.schemas)) {
  if (!Object.values(validators).includes(name)) validators[`validate${name}`] = name;
}
for (const [name, schema] of Object.entries(source.schemas)) {
  outputs.set(`contracts/json-schema/${name}.json`, json(schema));
  ajv.addSchema(schema, name);
}
const prefix = 'packages/contracts-ts/src/generated/';
outputs.set(`${prefix}api.ts`, astToString(await openapiTS(source.openapi)));
outputs.set(`${prefix}validators.js`, `// Generated by tools/contracts.mjs. Do not edit.\n${standaloneCode(ajv, validators)}\n`);
outputs.set(`${prefix}validators.d.ts`, `// Generated by tools/contracts.mjs. Do not edit.\nimport type { components } from './api.js';\n${Object.entries(validators).map(([name, schema]) => `export declare function ${name}(value: unknown): value is components['schemas']['${schema}'];`).join('\n')}\n`);
outputs.set(`${prefix}constants.ts`, `// Generated by tools/contracts.mjs. Do not edit.\nexport const API_VERSION = ${JSON.stringify(source.apiVersion)};\nexport const SCHEMA_VERSION = ${source.schemaVersion};\n`);
let changed = false;
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    const existing = await readFile(path, 'utf8').catch(() => null);
    if (existing !== content) { console.error(`Contract drift: ${path}`); changed = true; }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}
if (changed) process.exitCode = 1;
else console.log(process.argv.includes('--check') ? 'Contracts match Rust sources.' : 'Contracts generated.');
